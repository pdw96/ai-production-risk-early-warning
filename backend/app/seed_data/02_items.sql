-- 여기 값이 난수일 이유가 없다. 안전재고도 유효기간 설정기간도 리드타임 계수도
-- 사내 프로세스가 정하는 값이지 매일 바뀌는 값이 아니다 — 난수로 두면 어제 본
-- 화면과 오늘 본 화면의 숫자가 다르고, 그러면 「왜 달라졌나」를 물을 수 없다.
--
-- 품목 하나 추가가 한 줄 추가다. 코드를 몰라도 고칠 수 있는 것이 이 파일의
-- 이득이고, 그 이득이 없으면 SQL 로 내릴 이유도 없다.
--
-- 접두가 유형을 말한다(지적 ⑯) — FG-/SF-/RM-. 공정은 접두가 아니라 열이며,
-- 그래야 공정이 바뀔 때 품목 코드를 바꾸지 않는다.
--
-- 완제품의 안전재고는 비어 있다. 품목 통합으로 칸이 **생겼을 뿐** 아직 정한
-- 사람이 없기 때문이다. 없는 값을 지어내면 화면에서는 있는 것처럼 보인다.
--
-- 반제품(SF-)은 아직 없다. 표는 자리를 내주었지만 반제품 오더가 생기는 것은
-- 생산 흐름 단계의 일이고, 지금 넣으면 가리킬 오더도 검사도 없는 품목이 된다.


