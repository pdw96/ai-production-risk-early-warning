#!/usr/bin/env bash
# 물려받은 `DATABASE_URL` 이 **지난 실행에서 우리가 고른 것**인지 답한다.
#
# 왜 물어야 하는가. 우리가 고른 주소는 다시 골라야 한다 — 호스트나 컨테이너가
# 다시 뜨면 그 소켓 뒤의 서버는 내려가 있고, 서버를 세우는 것은 `database.sh`
# 하나뿐이라 그 자리를 건너뛰면 준비가 죽은 서버를 향해 돈다. 반대로 **사람이
# 준 주소는 그대로 둔다** — 남의 서버를 우리가 기동할 일이 아니다.
#
# 표식이 그 둘을 갈랐는데, 표식이 `1` 이라는 사실만 들고 있으면 갈리지 않는다.
# 지난 세션의 파일을 읽은 셸에서 개발자가 `export DATABASE_URL=...` 로 다른
# 데이터베이스를 고르면 표식은 여전히 `1` 이고, 그러면 **방금 사람이 고른 주소가
# 버려진다.** 그래서 표식은 자기가 표시하는 **그 값**을 들고 다니고, 여기서는
# 지금 값과 견준다. 값이 다르면 사람이 갈아 끼운 것이므로 우리 것이 아니다.
#
# 이 판단이 `setup.sh`·`start.sh`·세션 시작 훅 세 곳에 있었고 셋이 같은 모양으로
# 틀려 있었다. 그래서 **정의를 하나로 둔다.**
production_risk_url_is_inherited_ours() {
  [ -n "${DATABASE_URL:-}" ] &&
    [ "${PRODUCTION_RISK_DATABASE_AUTOSELECTED:-}" = "${DATABASE_URL}" ]
}
